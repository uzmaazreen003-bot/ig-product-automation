"""Product selection, angles and captions.

Everything that ends up in a caption or on screen is taken from data/products.json.
No text is generated by an AI service, so nothing can be invented.
"""
from __future__ import annotations

import re
from datetime import datetime, timedelta, timezone

IST = timezone(timedelta(hours=5, minutes=30))
WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


def now_ist() -> datetime:
    return datetime.now(IST)


def format_for(dt: datetime, cfg: dict) -> str:
    return cfg["schedule_ist"][WEEKDAYS[dt.weekday()]]


def published_entries(history):
    return [h for h in history if h.get("status") == "published"]


def already_posted_on(history, date_str: str) -> bool:
    return any(h.get("date") == date_str for h in published_entries(history))


def pick_product(products, history, cfg, forced_id: str | None = None):
    if forced_id:
        for p in products:
            if p["id"] == forced_id:
                return p
        raise SystemExit(f"Unknown product id: {forced_id}")
    pub = published_entries(history)
    last, count = {}, {}
    for h in pub:
        pid = h["product_id"]
        last[pid] = max(last.get(pid, ""), h["date"])
        count[pid] = count.get(pid, 0) + 1
    gap = max(0, min(cfg.get("min_gap_products", 8), len(products) - 1))
    recent = {h["product_id"] for h in pub[-gap:]} if gap else set()
    pool = [(i, p) for i, p in enumerate(products) if p["id"] not in recent] or list(enumerate(products))
    pool.sort(key=lambda ip: (last.get(ip[1]["id"], ""), count.get(ip[1]["id"], 0), ip[0]))
    return pool[0][1]


def available_angles(product, fmt):
    angles = ["showcase"]
    if len(product.get("points", [])) >= 6:
        angles.append("benefit")
    if len(product.get("audience", [])) >= 2:
        angles.append("audience")
    return angles


def pick_angle(product, fmt, history):
    angles = available_angles(product, fmt)
    used = {}
    for h in published_entries(history):
        if h["product_id"] == product["id"]:
            used[h.get("angle")] = used.get(h.get("angle"), 0) + 1
    return min(angles, key=lambda a: (used.get(a, 0), angles.index(a)))


def times_promoted(product, history) -> int:
    return sum(1 for h in published_entries(history) if h["product_id"] == product["id"])


def _three(items, start=0):
    chunk = items[start:start + 3]
    return chunk if len(chunk) >= 3 else items[:3]


def reel_script(product, angle, nth):
    hooks = product["hooks"]
    hook = hooks[nth % len(hooks)]
    pts, aud = product["points"], product.get("audience", [])
    if angle == "audience":
        header, items = product.get("audience_title") or "Made for", aud[:3]
    elif angle == "benefit":
        header, items = "Also inside", _three(pts, 3)
    else:
        header, items = "What's inside", _three(pts, 0)
    return {"hook": hook, "header": header, "items": items}


def carousel_script(product, angle, nth):
    hooks = product["hooks"]
    hook = hooks[nth % len(hooks)]
    pts, aud = product["points"], product.get("audience", [])
    slides = [("cover", None, None)]
    if angle == "audience":
        slides.append(("list", product.get("audience_title") or "Made for", aud[:5]))
        slides.append(("list", "What's inside", pts[:5]))
    elif angle == "benefit":
        slides.append(("list", "Also inside", pts[2:7] if len(pts) >= 7 else pts[1:6]))
        if len(aud) >= 2:
            slides.append(("list", product.get("audience_title") or "Made for", aud[:5]))
    else:
        slides.append(("list", "What's inside", pts[:5]))
        if len(aud) >= 2:
            slides.append(("list", product.get("audience_title") or "Made for", aud[:5]))
    slides.append(("cta", None, None))
    return {"hook": hook, "slides": slides}


def clean_hashtags(tags, cfg):
    seen, out = set(), []
    for t in list(tags) + list(cfg.get("base_hashtags", [])):
        t = "#" + re.sub(r"[^A-Za-z0-9_]", "", t).lower()
        if len(t) > 1 and t not in seen:
            seen.add(t)
            out.append(t)
    return out[: cfg.get("max_hashtags", 12)]


def build_caption(product, angle, script, cfg, fmt):
    bullets = script["items"] if fmt == "reel" else None
    if bullets is None:
        first = next((s for s in script["slides"] if s[0] == "list"), None)
        bullets = (first[2] if first else product["points"])[:4]
    lines = [script["hook"], "", product["title"] + (f": {product['subtitle']}" if product.get("subtitle") else "")]
    lines.append("")
    lines += [f"✔ {b}" for b in bullets[:4]]
    lines.append("")
    info = []
    if cfg.get("show_price", True):
        info.append(f"{cfg.get('currency_symbol', '₹')}{product['price']}")
    if product.get("meta"):
        info.append(product["meta"])
    if info:
        lines.append("🛒 " + " · ".join(info))
    short_url = product["url"].replace("https://", "")
    lines.append(f"🔗 Link in bio · {short_url}")
    if product.get("disclaimer"):
        lines += ["", product["disclaimer"]]
    lines += ["", " ".join(clean_hashtags(product.get("tags", []), cfg))]
    caption = "\n".join(lines)
    if len(caption) > 2200:
        raise ValueError(f"Caption too long ({len(caption)}) for product {product['id']}")
    return caption
